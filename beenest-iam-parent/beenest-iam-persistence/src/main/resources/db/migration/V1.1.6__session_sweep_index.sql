-- =====================================================================
-- V1.1.6 会话存储迁移到共享 Redis 后的配套索引
-- ---------------------------------------------------------------------
-- 背景:
--   浏览器会话状态改由 Redis 承载(会话标识由平台签发并随 Cookie 下发),
--   平台得以横向扩容:任意实例都能接着服务同一个会话。
--   随之而来的是"僵尸会话"问题——Redis 键会随空闲超时自然消失,
--   而 iam_user_session 里的行只在会话被显式结束时才改写。
--   用户关掉浏览器、实例重启等场景都会留下状态仍为 ACTIVE 的行,
--   "在线会话"列表随之失真,强制下线与审计也跟着不准。
--   巡检任务按状态捞取 ACTIVE 的行,逐条核对 Redis 键是否还在。
-- 本脚本为配套索引,让这条跨域查询不必全表扫描。
-- =====================================================================

-- 只索引仍处于 ACTIVE 的行:这类行是少数,索引体积小且随会话结束自动收缩
CREATE INDEX IF NOT EXISTS idx_iam_user_session_active
    ON iam_user_session(id) WHERE state = 'ACTIVE' AND deleted = FALSE;
