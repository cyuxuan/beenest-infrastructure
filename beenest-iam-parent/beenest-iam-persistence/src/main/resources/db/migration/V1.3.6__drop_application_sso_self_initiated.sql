-- V1.3.6 移除应用"自发起"标记
--   sso_self_initiated 用来区分两条启动路径:门户代发授权地址、应用自己发起。
--   门户代发这条路在协议上不成立:state/nonce/code_challenge 的验证方都是应用,
--   门户拿不到应用的会话,生成的值应用无法校验,只能选择跳过校验或拒绝回调。
--   门户现在只把浏览器送到应用入口地址(entry_url),授权请求一律由应用自己发起,
--   这条区分随之消失。
-- ============================================================

ALTER TABLE iam_application_service
    DROP COLUMN IF EXISTS sso_self_initiated;
